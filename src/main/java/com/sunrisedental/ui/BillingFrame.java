    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String appointmentText = txtAppointmentId.getText().trim();

        if (appointmentText.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please enter Appointment ID.",
                "Missing Appointment ID",
                JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int appointmentId;

        try {

            appointmentId = Integer.parseInt(appointmentText);

            if (appointmentId <= 0) {
                throw new NumberFormatException();
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Please enter a valid numeric Appointment ID.",
                "Invalid Appointment ID",
                JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        try {

            BillDTO bill =
            ServiceClient.billing()
            .calculateBill(appointmentId);

            if (bill == null) {

                JOptionPane.showMessageDialog(
                    this,
                    "Appointment not found or treatment price is unavailable.",
                    "Bill Not Found",
                    JOptionPane.WARNING_MESSAGE
                );

                clearBill();

                return;
            }

            txtPatientName.setText(
                bill.patientName
            );

            txtDentistName.setText(
                bill.dentistName
            );

            txtTreatment.setText(
                bill.treatmentType
            );

            // Treatment Cost
            txtTreatmentCost.setText(
                String.format(
                    "Rs. %.2f",
                    bill.treatmentCost
                )
            );

            // Total
            txtTotal.setText(
                String.format(
                    "Rs. %.2f",
                    bill.total
                )
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                this,
                "Unable to retrieve bill.\n\n"
                + e.getMessage(),
                "Billing Error",
                JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }//GEN-LAST:event_btnSearchActionPerformed

