    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        if (txtPatientName.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please search an appointment first.",
                "No Bill",
                JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        PrinterJob printerJob = PrinterJob.getPrinterJob();

        printerJob.setPrintable(new Printable() {

            @Override
            public int print(
                java.awt.Graphics graphics,
                PageFormat pageFormat,
                int pageIndex) throws PrinterException {

                if (pageIndex > 0) {

                    return NO_SUCH_PAGE;
                }

                Graphics2D g2 =
                (Graphics2D) graphics;

                g2.translate(
                    pageFormat.getImageableX(),
                    pageFormat.getImageableY()
                );

                int y = 40;

                // Clinic name
                g2.setFont(
                    new Font(
                        "Arial",
                        Font.BOLD,
                        20
                    )
                );

                g2.drawString(
                    "SUNRISE DENTAL CLINIC",
                    50,
                    y
                );

                y += 30;

                // Bill title
                g2.setFont(
                    new Font(
                        "Arial",
                        Font.BOLD,
                        16
                    )
                );

                g2.drawString(
                    "PATIENT BILL",
                    50,
                    y
                );

                y += 40;

                g2.setFont(
                    new Font(
                        "Arial",
                        Font.PLAIN,
                        13
                    )
                );

                // Appointment ID
                g2.drawString(
                    "Appointment ID : "
                    + txtAppointmentId.getText(),
                    50,
                    y
                );

                y += 25;

                // Patient
                g2.drawString(
                    "Patient Name   : "
                    + txtPatientName.getText(),
                    50,
                    y
                );

                y += 25;

                // Dentist
                g2.drawString(
                    "Dentist Name   : "
                    + txtDentistName.getText(),
                    50,
                    y
                );

                y += 25;

                // Treatment
                g2.drawString(
                    "Treatment      : "
                    + txtTreatment.getText(),
                    50,
                    y
                );

                y += 25;

                // Treatment cost
                g2.drawString(
                    "Treatment Cost : "
                    + txtTreatmentCost.getText(),
                    50,
                    y
                );

                y += 30;

                g2.drawString(
                    "-----------------------------------",
                    50,
                    y
                );

                y += 25;

                // Total
                g2.setFont(
                    new Font(
                        "Arial",
                        Font.BOLD,
                        15
                    )
                );

                g2.drawString(
                    "TOTAL AMOUNT  : "
                    + txtTotal.getText(),
                    50,
                    y
                );

                y += 45;

                g2.setFont(
                    new Font(
                        "Arial",
                        Font.PLAIN,
                        12
                    )
                );

                g2.drawString(
                    "Thank you for choosing Sunrise Dental Clinic.",
                    50,
                    y
                );

                return PAGE_EXISTS;
            }
        });

        boolean printConfirmed =
        printerJob.printDialog();

        if (printConfirmed) {

            try {

                printerJob.print();

                JOptionPane.showMessageDialog(
                    this,
                    "Bill printed successfully.",
                    "Print Bill",
                    JOptionPane.INFORMATION_MESSAGE
                );

            } catch (PrinterException e) {

                JOptionPane.showMessageDialog(
                    this,
                    "Printing failed.\n\n"
                    + e.getMessage(),
                    "Print Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }
        
